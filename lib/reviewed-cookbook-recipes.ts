export function installReviewedCookbookPack(existing: Recipe[], installedRecipePacks: string[] = []) {
  if (installedRecipePacks.includes(REVIEWED_COOKBOOK_PACK_ID)) {
    return { recipes: existing, installedRecipePacks, addedCount: 0 };
  }
  const ids = new Set(existing.map(recipe => recipe.id));
  // Same-titled recipes from other books remain separate; never overwrite household edits.
  const additions = reviewedCookbookRecipes.filter(recipe => !ids.has(recipe.id));
  return {
    recipes: [...existing, ...additions],
    installedRecipePacks: [...installedRecipePacks, REVIEWED_COOKBOOK_PACK_ID],
    addedCount: additions.length
  };
}
